/**
 * Regenerate `lib/curated-data.js` from `data/catalog.json`.
 *
 * The curated registry is data, not code: it is a list of public `SKILL.md`
 * files whose raw URLs were fetched and confirmed before being written down.
 * Keeping the JSON as the source of truth and generating the module from it
 * means the registry can be re-verified and refreshed without editing a
 * hand-maintained literal, and the generator is the place that checks a card is
 * actually installable before it reaches the shop.
 *
 * Usage: `node scripts/build-curated.mjs`
 *
 * @module skills-market/scripts/build-curated
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')

/** Every category the shop groups by, in display order. */
const CATEGORIES = ['frontend', 'layout', 'debug', 'prompt', 'docs', 'testing', 'git']

const rows = JSON.parse(readFileSync(path.join(root, 'data', 'catalog.json'), 'utf8'))
if (!Array.isArray(rows)) throw new Error('data/catalog.json must be an array')

const seen = new Set()
const entries = rows.map((row) => {
  const required = ['id', 'name', 'title', 'description', 'author', 'category', 'repo', 'branch', 'path', 'raw']
  for (const key of required) {
    if (typeof row[key] !== 'string' || row[key].trim() === '') {
      throw new Error(`card ${row.id ?? '(no id)'} is missing ${key}`)
    }
  }
  if (seen.has(row.id)) throw new Error(`duplicate card id: ${row.id}`)
  seen.add(row.id)

  const [owner, repo] = row.repo.split('/')
  if (owner === undefined || repo === undefined) throw new Error(`card ${row.id} has a bad repo: ${row.repo}`)

  const expected = `https://raw.githubusercontent.com/${owner}/${repo}/${row.branch}/${row.path}`
  if (row.raw !== expected) throw new Error(`card ${row.id}: raw URL does not match repo/branch/path\n  got  ${row.raw}\n  want ${expected}`)

  if (!CATEGORIES.includes(row.category)) throw new Error(`card ${row.id} has an unknown category: ${row.category}`)

  const tags = Array.isArray(row.tags) ? row.tags.filter((tag) => typeof tag === 'string' && tag.trim() !== '') : []
  if (tags.length === 0) throw new Error(`card ${row.id} has no tags`)

  return {
    id: row.id,
    name: row.name,
    title: row.title,
    description: row.description,
    tags,
    author: row.author,
    category: row.category,
    repo: row.repo,
    branch: row.branch,
    path: row.path,
    raw: row.raw,
    license: typeof row.license === 'string' ? row.license : null,
  }
})

const body = entries
  .map((entry) => {
    const lines = Object.entries(entry).map(([key, value]) => `    ${key}: ${JSON.stringify(value)},`)
    return `  {\n${lines.join('\n')}\n  },`
  })
  .join('\n')

const module = `/**
 * The bundled curated registry — generated by \`scripts/build-curated.mjs\`.
 *
 * Do not edit by hand: change \`data/catalog.json\` and regenerate. Every entry
 * here points at a public \`SKILL.md\` whose raw URL was fetched and confirmed,
 * and the generator refuses to emit a card whose \`raw\` URL disagrees with its
 * \`repo\`/\`branch\`/\`path\`, so a typo cannot ship as a broken Install button.
 *
 * These are the shop's own shelves: they work with no API key, no rate limit and
 * no third-party availability, which is what makes the Install button reliable
 * on a fresh machine. The card shape is applied by \`lib/curated.js\`, which owns
 * everything about these entries that is logic rather than data.
 *
 * @module skills-market/lib/curated-data
 */

/** Display order of the categories these cards are grouped into. */
export const CATEGORIES = ${JSON.stringify(CATEGORIES)}

/**
 * The bundled cards.
 * @type {ReadonlyArray<{ id: string, name: string, title: string, description: string, tags: string[], author: string, category: string, repo: string, branch: string, path: string, raw: string, license: string | null }>}
 */
export const CURATED = [
${body}
]
`

writeFileSync(path.join(root, 'lib', 'curated-data.js'), module, 'utf8')

const byCategory = entries.reduce((accumulator, entry) => {
  accumulator[entry.category] = (accumulator[entry.category] ?? 0) + 1
  return accumulator
}, {})

process.stdout.write(`wrote lib/curated-data.js with ${entries.length} cards\n`)
process.stdout.write(`${JSON.stringify(byCategory)}\n`)
